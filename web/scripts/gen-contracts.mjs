// Writes src/generated/contracts.ts from the Foundry build (run `forge build` in the repo root
// first). Contract names, the salt and scETC's constructor strings come from script/Deploy.s.sol,
// the ABIs and bytecode from ../out. The addresses are computed as the script computes them, with
// the CREATE2 deployer, and the verifier code hash is keccak256 of its runtime bytecode, what
// eth_getCode returns at that address.
import { writeFileSync } from "node:fs";
import { concatHex, encodeAbiParameters, getContractAddress, keccak256, stringToHex } from "viem";
import { artifact, deployInfo, fail } from "./deploy-info.mjs";

const CREATE2_DEPLOYER = "0x4e59b44847b379578588920ca78fbf26c0b4956c";
const info = deployInfo();
const verifier = artifact(info.verifier);
const ledger = artifact(info.ledger);
const iface = artifact("ILeanSphincsVerifier");

const runtime = verifier.deployedBytecode.object;
if (Object.keys(verifier.deployedBytecode.immutableReferences ?? {}).length) fail(`${info.verifier} has immutables, so its code hash isn't fixed`);
const salt = keccak256(stringToHex(info.salt));
const at = (init) => getContractAddress({ opcode: "CREATE2", from: CREATE2_DEPLOYER, salt, bytecode: init });
const verifierAddress = at(verifier.bytecode.object);
const ledgerInit = concatHex([
  ledger.bytecode.object,
  encodeAbiParameters([{ type: "address" }, { type: "string" }, { type: "string" }], [verifierAddress, info.ledgerName, info.ledgerSymbol]),
]);
const ledgerAddress = at(ledgerInit);

for (const fn of ["accountOf", "transfer", "withdraw", "transferDigest", "withdrawDigest", "balanceOf", "nonces"])
  if (!ledger.abi.some((x) => x.name === fn)) fail(`${info.ledger} has no ${fn}(), which the page calls`);
for (const ev of ["Memo", "FeePaid", "Transfer"])
  if (!ledger.abi.some((x) => x.type === "event" && x.name === ev)) fail(`${info.ledger} has no ${ev} event, which the page reads`);

const j = (x) => JSON.stringify(x, null, 2);
writeFileSync(
  new URL("../src/generated/contracts.ts", import.meta.url),
  `// Generated by scripts/gen-contracts.mjs from script/Deploy.s.sol and the Foundry build. Do not edit.

export const ledgerAbi = ${j(ledger.abi)} as const;

export const verifierAbi = ${j(iface.abi)} as const;

export const VERIFIER_NAME = ${j(info.verifier)};
/** keccak256 of ${info.verifier}'s runtime bytecode (${(runtime.length - 2) / 2} bytes). */
export const VERIFIER_CODE_HASH = "${keccak256(runtime)}" as const;
export const VERIFIER_ADDRESS = "${verifierAddress}" as const;

export const LEDGER_NAME = ${j(info.ledgerName)};
export const LEDGER_SYMBOL = ${j(info.ledgerSymbol)};
export const LEDGER_ADDRESS = "${ledgerAddress}" as const;

/** CREATE2 salt preimage in script/Deploy.s.sol. */
export const DEPLOY_SALT = ${j(info.salt)};
`,
);
console.log(`${info.verifier} at ${verifierAddress}, code hash ${keccak256(runtime)}`);
console.log(`${info.ledger} (${info.ledgerName}, ${info.ledgerSymbol}) at ${ledgerAddress}`);
