// Writes src/generated/contracts.ts from the Foundry build in ../out (run `forge build` first).
// The ABIs come from the compiled contracts and the verifier code hash is keccak256 of the
// verifier's deployed bytecode, which is what eth_getCode returns at the CREATE2 address.
import { readFileSync, writeFileSync } from "node:fs";
import { keccak256 } from "viem";

const out = new URL("../../out/", import.meta.url);
const art = (file, name) => JSON.parse(readFileSync(new URL(`${file}/${name}.json`, out), "utf8"));

const wallet = art("LeanSphincsWallet.sol", "LeanSphincsWallet");
const factory = art("LeanSphincsWalletFactory.sol", "LeanSphincsWalletFactory");
const iface = art("ILeanSphincsVerifier.sol", "ILeanSphincsVerifier");
const verifier = art("LeanSphincs-LayeredAsm.sol", "LeanSphincsLayeredAsm");

const runtime = verifier.deployedBytecode.object;
if (Object.keys(verifier.deployedBytecode.immutableReferences ?? {}).length) throw new Error("verifier has immutables");
const codeHash = keccak256(runtime);

const j = (x) => JSON.stringify(x, null, 2);
writeFileSync(
  new URL("../src/generated/contracts.ts", import.meta.url),
  `// Generated by scripts/gen-contracts.mjs from the Foundry build. Do not edit.

export const walletAbi = ${j(wallet.abi)} as const;

export const factoryAbi = ${j(factory.abi)} as const;

export const verifierAbi = ${j(iface.abi)} as const;

/** keccak256 of LeanSphincsLayeredAsm's runtime bytecode (${(runtime.length - 2) / 2} bytes). */
export const VERIFIER_CODE_HASH = "${codeHash}" as const;
`,
);
console.log("verifier code hash", codeHash);
